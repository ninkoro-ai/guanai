function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function renderTable(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const pct = widths.map((w) => `${((w / total) * 100).toFixed(2)}%`).join(' ');
  const thead = headers.map((h) => `<th>${esc(h)}</th>`).join('');
  const body = rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('');
  return `<table style="width:100%;border-collapse:collapse;margin:10px 0;" role="presentation"><colgroup>${widths.map((w) => `<col style="width:${((w / total) * 100).toFixed(2)}%">`).join('')}</colgroup><thead><tr>${thead}</tr></thead><tbody>${body}</tbody></table>`;
}

function renderItem(item) {
  switch (item.t) {
    case 'h2':
      return `<h2>${esc(item.text)}</h2>`;
    case 'p':
      return `<p>${esc(item.text)}</p>`;
    case 'bullets':
      return `<ul>${item.items.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`;
    case 'steps':
      return `<ol>${item.items.map((x) => `<li>${esc(x)}</li>`).join('')}</ol>`;
    case 'note':
      return `<div class="note"><b>${esc(item.label)}：</b>${esc(item.text).replace(/\n/g, '<br>')}</div>`;
    case 'figure':
      return `<figure><img src="${img(item.file)}" alt="${esc(item.caption)}"><figcaption>${esc(item.caption)}</figcaption></figure>`;
    case 'table':
      return renderTable(item.headers, item.rows, item.widths);
    case 'qa':
      return item.rows.map(([q, a]) => `<p class="qa"><b>${esc(q)}</b><br>${esc(a)}</p>`).join('');
    default:
      return '';
  }
}

